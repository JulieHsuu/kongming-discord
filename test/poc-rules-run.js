import assert from 'node:assert/strict';
import { protectPoc, hasTestLeakage } from '../src/poc-rules.js';
const c = { name: '功能測試公司', profile: { budget: 300 }, facts: [{ label: '表列設備合計', value: '4萬元' }] };
const input = { title: 'POC', team: [{ side: '資策會', role: '資策會準備模型' }], risks: [{ risk: '1200張可能是測試資料' }], cost_estimate: '設備不是全部成本', timeline: [{ task: '以驗證集調整模型' }] };
const d = protectPoc(input, c);
assert.match(d.cost_estimate, /296 萬元用途尚未列明/);
assert.equal(d.team[0].side, '技術團隊（待確認）');
assert.match(d.risks[0].risk, /已標示為虛構測試資料/);
assert.match(d.planning_notes.join(''), /時程.*均待確認/);
assert.match(d.planning_notes.join(''), /調參僅使用驗證集/);
assert.equal(input.team[0].side, '資策會');
assert.throws(() => protectPoc({ title: '錯誤', timeline: [{ task: '以凍結測試集調整模型' }] }, c), /已停止交付/);
assert.ok(!protectPoc({ title: '正式案件' }, { name: '真實企業' }).planning_notes.join('').includes('虛構'));
console.log('POC rules: 8 assertions passed');
for (const text of ['不得使用凍結測試集調整模型', '避免利用測試集調參', '以凍結測試集驗收，不得調整模型', '使用驗證集調整模型，測試集只供最終驗收', '測試集不用於調參']) assert.equal(hasTestLeakage(text), false, text);
for (const text of ['以凍結測試集調整模型', '使用測試集選型', '測試集用於調參', '不得使用測試集調參，但以測試集調整模型']) assert.equal(hasTestLeakage(text), true, text);
console.log('POC leakage: 9 clause and negation checks passed');
const revised = protectPoc({ title: '指標測試', kpi: [{ name: '良品誤報率', basis: '不良或需複核÷良品', unit: '秒' }, { name: '人工複核率', basis: '待補' }], team: [{ side: '建議技術團隊（承接單位待確認）' }] }, c);
assert.match(revised.kpi[0].basis, /良品不計入誤報/);
assert.equal(revised.kpi[0].unit, '%');
assert.match(revised.kpi[1].basis, /分開計算/);
assert.equal(revised.team[0].side, '技術團隊（待確認）');
const { attachmentName } = await import('../src/files/readers.js');
assert.equal(attachmentName({ title: '功能測試公司_資料', name: 'abcd.xlsx' }), '功能測試公司_資料.xlsx');
assert.equal(attachmentName({ name: '原檔.xlsx', transportName: 'abcd.xlsx' }), '原檔.xlsx');
assert.equal(attachmentName({ name: 'abcd.xlsx' }), 'abcd.xlsx');
console.log('KPI, wording and original attachment names: 7 checks passed');
